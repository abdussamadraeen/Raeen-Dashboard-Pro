const domCache = new Map();

export const dom = {};
for (const [key, id] of Object.entries(domConfig)) {
    Object.defineProperty(dom, key, {
        get() {
            let ref = domCache.get(key);
            let el = ref?.deref();
            if (!el || (el.nodeType === 1 && !el.isConnected)) {
                if (typeof id === 'string') {
                    el = document.getElementById(id);
                } else {
                    el = id; // handle querySelectorAll which might be NodeList
                }
                if (el) domCache.set(key, new WeakRef(el));
            }
            return el;
        }
    });
}
